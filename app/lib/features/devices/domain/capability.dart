/// Something a device can report or be told to do.
///
/// The UI is generated from capabilities: a control is shown only when the
/// device declares the capability, so unsupported commands are never offered.
enum Capability {
  power,
  brightness,
  rgb,
  rgbw,
  hsColor,
  xyColor,
  colorTemperature,
  transition,
  targetTemperature,
  targetTemperatureRange,
  currentTemperature,
  heating,
  cooling,
  hvacMode,
  fanMode,
  swingMode,
  presetMode,
  humidity,
  targetHumidity,
  open,
  close,
  stop,
  position,
  tilt,
  lock,
  unlock,
  arm,
  disarm,
  trigger,
  battery,
  powerConsumption,
  energyConsumption,
  voltage,
  current,
  frequency,
  mediaPlay,
  mediaPause,
  mediaStop,
  mediaNext,
  mediaPrevious,
  volume,
  mute,

  /// Volume one step up or down (no level).
  volumeStep,
  soundMode,

  /// Takes remote-control keys ([DeviceLimits.tvKeys]).
  tvKeys,
  sourceSelection,
  mediaSeek,
  shuffle,
  repeat,
  cameraStream,
  cameraSnapshot,
  fanSpeed,
  oscillate,
  vacuumStart,
  vacuumPause,
  vacuumReturnHome,
  selectOption,
  numberValue,
}
